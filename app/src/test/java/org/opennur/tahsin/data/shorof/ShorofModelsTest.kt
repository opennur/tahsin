@file:Suppress("MaxLineLength")

package org.opennur.tahsin.data.shorof

import org.junit.Assert.assertEquals
import org.junit.Test

class ShorofModelsTest {
    @Test
    fun `model menyimpan pola tasrif dan latihan`() {
        val pattern = ShorofPattern("ك ت ب", "k-t-b", "فَعَلَ", "faʿala", "Dasar", "Basic", "menulis", "write", "كَتَبَ", "kataba")
        val row = ShorofConjugation("هُوَ", "huwa", "كَتَبَ", "يَكْتُبُ", "اُكْتُبْ")
        val rule = ShorofRule("Akar", "Root", "Penjelasan", "Explanation", "كَتَبَ", "kataba", "menulis", "write")
        val exercise = ShorofChoiceExercise("Pilih", "Choose", "كَتَبَ", "kataba", listOf("A"), listOf("A"), 0)
        val lesson = ShorofLesson("1-1", "Akar", "Root", "الْجِذْرُ", "Intro", "Intro", listOf(rule), listOf(pattern), listOf(row), listOf(exercise))
        val level = ShorofLevel(1, "Dasar", "Basic", "الْأَسَاسُ", listOf(lesson))
        val catalog = ShorofCatalog(1, listOf(level))
        val session = ShorofSessionExercise("1-1", exercise)
        assertEquals(1, catalog.schemaVersion)
        assertEquals("k-t-b", pattern.rootLatin)
        assertEquals("فَعَلَ", pattern.wazan)
        assertEquals("faʿala", pattern.wazanLatin)
        assertEquals("Dasar", pattern.formId)
        assertEquals("Basic", pattern.formEn)
        assertEquals("menulis", pattern.meaningId)
        assertEquals("write", pattern.meaningEn)
        assertEquals("كَتَبَ", pattern.exampleAr)
        assertEquals("kataba", pattern.exampleLatin)
        assertEquals("هُوَ", row.pronounAr)
        assertEquals("huwa", row.pronounLatin)
        assertEquals("كَتَبَ", row.past)
        assertEquals("يَكْتُبُ", row.present)
        assertEquals("اُكْتُبْ", row.imperative)
        assertEquals("Akar", rule.titleId)
        assertEquals("Root", rule.titleEn)
        assertEquals("Penjelasan", rule.explanationId)
        assertEquals("Explanation", rule.explanationEn)
        assertEquals("كَتَبَ", rule.exampleAr)
        assertEquals("kataba", rule.exampleLatin)
        assertEquals("menulis", rule.exampleId)
        assertEquals("write", rule.exampleEn)
        assertEquals("Root", lesson.titleEn)
        assertEquals("1-1", lesson.id)
        assertEquals("Akar", lesson.titleId)
        assertEquals("الْجِذْرُ", lesson.titleAr)
        assertEquals("Intro", lesson.introId)
        assertEquals("Intro", lesson.introEn)
        assertEquals(listOf(rule), lesson.rules)
        assertEquals(listOf(pattern), lesson.patterns)
        assertEquals(listOf(row), lesson.conjugations)
        assertEquals("Basic", level.titleEn)
        assertEquals(1, level.id)
        assertEquals("Dasar", level.titleId)
        assertEquals("الْأَسَاسُ", level.titleAr)
        assertEquals(listOf(lesson), level.lessons)
        assertEquals(exercise, session.exercise)
        assertEquals("1-1", session.lessonId)
        assertEquals("Pilih", exercise.promptId)
        assertEquals("Choose", exercise.promptEn)
        assertEquals("كَتَبَ", exercise.promptAr)
        assertEquals("kataba", exercise.promptLatin)
        assertEquals(listOf("A"), exercise.optionsId)
        assertEquals(listOf("A"), exercise.optionsEn)
    }
}
